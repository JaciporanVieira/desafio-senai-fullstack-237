CREATE TABLE public.jogadores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idade INTEGER NOT NULL,
    agilidade INTEGER NOT NULL,
    valor_base NUMERIC(6,2) NOT NULL,
    clube_id INTEGER,
    condicao VARCHAR(20) NOT NULL,
    defesa INTEGER NOT NULL,
    drible INTEGER NOT NULL,
    nome VARCHAR(100) NOT NULL,
    velocidade INTEGER NOT NULL,
    passe INTEGER NOT NULL,
    fisico INTEGER NOT NULL,
    posicao VARCHAR(3) NOT NULL,
    potencial INTEGER NOT NULL,
    finalizacao INTEGER NOT NULL,
    excluido_em TIMESTAMP,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT players_age_check
        CHECK (idade BETWEEN 16 AND 45),

    CONSTRAINT players_agility_check
        CHECK (agilidade BETWEEN 1 AND 100),

    CONSTRAINT players_condition_check
        CHECK (condicao IN ('APTO', 'MAL_CONDICIONADO', 'DOENTE')),

    CONSTRAINT players_defending_check
        CHECK (defesa BETWEEN 1 AND 99),

    CONSTRAINT players_dribbling_check
        CHECK (drible BETWEEN 1 AND 99),

    CONSTRAINT players_pace_check
        CHECK (velocidade BETWEEN 1 AND 99),

    CONSTRAINT players_passing_check
        CHECK (passe BETWEEN 1 AND 99),

    CONSTRAINT players_physical_check
        CHECK (fisico BETWEEN 1 AND 99),

    CONSTRAINT players_position_check
        CHECK (posicao IN ('GOL', 'ZAG', 'LAT', 'MEI', 'ATA')),

    CONSTRAINT players_potential_check
        CHECK (potencial BETWEEN 1 AND 99),

    CONSTRAINT players_shooting_check
        CHECK (finalizacao BETWEEN 1 AND 99)
);
